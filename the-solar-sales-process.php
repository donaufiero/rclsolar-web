			<p><h5>Step #1 - Professional consultation</h5></br>
			One of our professional Solar specialist's will contact you via telephone to gather the following information:</br>
				<ul>
					<li>Determine Solar PV lease or purchase option</li>
					<li>12 months historical energy usage</li>
					<li>Locate your site address via Google Image</li>
					<li>Discuss Solar roof or ground mount options</li>
					<li>Design your Solar Panel System based upon information specifically for your home</li>
					<li>Schedule an in-home appointment to present proposal</li>
				</ul>
			</p>
			<p>
				<h5>Step #2 - SOLAR PANEL DESIGN</h5>	</br>
					One of our Certified SOLAR design technician will visit your site and verify the following information:
				<ul>
					<li>Roof conditions and integrity (roof mounted systems)</li>
					<li>The corrent orientation and surface area measurements</li>
					<li>Evaluate shade conditions at the solar panels installation location</li>
					<li>Measure and design your SOLAR PANEL Array</li>
					<li>Your Solar Specialist will present you with the design for your approval</li>
					<li>We will assemble a unique solar energy system for your home or business, obtain all necessary permits to complete your solar panel installation.</li>
				</ul>	
		</p>
	  	<p>
			<h5>Step #3 - EXPERT SOLAR PANEL INSTALLATION</h5></br>
				Upon all state and local approvals RCL Enterprises will contact you to review your solar panel installation schedule, at which time a responsible person will need to be on site. Here is what you should expect:</br>
				Due to some local New Jersey Townships inspections, installations may require a two day installation.
			<ul>
			<li>Day 1:</li>
				<li>The RCL Enterprises SOLAR Installation team will install all of the racking and inverters. If required RCL Enterprises will schedule local rough inspections.</li>
			</ul>
			<ul>
				<li>Day 2:</li>
				<li>The RCL Enterprises SOLAR Installation team will install the solar panels and monitoring, if required Commission and test the SOLAR PANEL System
					Upon completion RCL Enterprises will schedule final inspections and notify you of the inspection date.</li>
			</ul>
	  	</p>
		<p>
			<h5>Step #4 - SOLAR PANEL SYSTEM  ACTIVATION AND MONITORING</h5> </br>
				Congratulations your Solar Panels have been installed! Here is what you should expect next:</br>
				 1 to 2 weeks after your solar panel installation RCL Enterprises will receive the required Certificate of Approval from your municipality. RCL Enterprises will file the final interconnection with your current utility company to release the solar net meter. This process may take 3 to 4 weeks dependent upon your utility company. RCL Enterprises will contact you when it is time to activate your system. Monitoring begins with your leasing company at this time. Now is you can enjoy the benefits of clean, renewable SOLAR energy.
